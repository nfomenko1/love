//  КОНТЕНТ КНИГИ
//  Единственное место, где задаются страницы. Движок (src/book)
//  ничего не знает о конкретных страницах.
//
//  Книга появляется закрытой, раскрывается и листается прокруткой.
//  Первый разворот: слева — внутренняя сторона обложки (inside),
//  справа — первая страница из `pages` (оглавление).
//
//  Каждый элемент `pages` — ОДНА сторона листа. В развороте нечётные
//  страницы (1, 3, 5…) справа, чётные — слева. Последняя страница
//  автоматически ставится справа (при необходимости перед ней
//  добавляется чистый лист).
//
//  cover — тиснение на лицевой стороне закрытой книги: title, names.
//  Внутренняя сторона обложки — чистая, только маленький орнамент.
//
//  Общие поля страниц:
//    id        — уникальная строка
//    type      — шаблон (см. ниже)
//    numbered  — показывать ли номер страницы (по умолчанию true)
//    numberLabel — свой знак вместо номера (например '· · ·')
//
//  Шаблоны:
//    'blank'       — чистая страница
//    'text'        — clean editorial page (текстовая колонка)
//    'ornament'    — decorative page (тонкие линии, контур сердца, свет)
//    'photo'       — одна большая фотография           photos: [{ src, alt }]
//    'photo-text'  — фотография + текст                 photos: [{ src, alt }]
//    'photo-pair'  — две фотографии                     photos: [{…}, {…}]
//    'typography'  — крупная типографская композиция    numeral: '01'
//    'spread'      — переходный декоративный разворот   half: 'left' | 'right'
//                    (две соседние страницы: чётная — left, следующая — right)
//    'moment'      — минималистичная страница под особенный момент
//    'toc'         — оглавление    title, entries: [{ num, title? } | null (пауза)]
//    'chapter'     — текст раздела  numeral, title, blocks: ['абзац' | { text, accent }]
//    'photo-full'  — одна фотография на всю страницу    photos: [{ src, alt }]
//    'final'       — финальная страница                 title (\n — перенос), subtitle
//    'album'       — страница фотоальбома               photos: [{ src, ratio, x, y, w }]
//
//  Фото: файлы кладутся в public/photos/, путь — 'photos/имя.webp' (~1200×1600, WebP).
//  Если src не задан — рисуется заглушка PHOTO.
// ─────────────────────────────────────────────────────────────

